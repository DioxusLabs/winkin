//! A few representative codepoints for each script.
//!
//! Enough to ask a font "can you draw this script?" without carrying the
//! whole character database. The fontconfig backend turns them into an
//! `FcCharSet`, which is how a script is stated to fontconfig exactly rather
//! than by proxy through a language.
//!
//! # How these were chosen
//!
//! The first eight assigned letters of each script — General_Category `Lu`,
//! `Ll`, `Lt`, `Lm` or `Lo`, in codepoint order — which lands on the core
//! alphabet for almost every one. `generated_entries_still_match_unicode`
//! regenerates the table and fails if it drifts.
//!
//! The rule has no notion of how *established* a character is, so it
//! sometimes lands on an archaic range or a recent addition that real fonts
//! for the script do not carry. Those entries are overridden, each with its
//! reason at the entry. Since `FC_CHARSET` puts these codepoints in front of
//! fontconfig, a sample nothing implements demotes every font that would
//! otherwise have won — so the failure mode is always a false negative, and
//! each platform's `no_sample_codepoint_is_an_outlier` test catches it, with
//! `report_outliers`.

