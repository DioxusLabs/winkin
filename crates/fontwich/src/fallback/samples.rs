/// Scripts whose entry is hand-picked rather than generated.
///
/// Each is justified at its entry above, and each was chosen because a font
/// that draws the script in full covered little or none of the generated
/// range — a false negative is the failure mode that matters here.
#[cfg(test)]
const OVERRIDDEN: &[[u8; 4]] = &[
    *b"Arab", *b"Cans", *b"Cyrl", *b"Geor", *b"Grek", *b"Hang", *b"Hani", *b"Hans", *b"Hant",
    *b"Jpan", *b"Kore", *b"Laoo", *b"Mlym", *b"Mtei",
];

/// Every script this table has samples for.
///
/// Only the sample-quality checks walk the whole table, and there is one per
/// platform that can measure font coverage — DirectWrite, fontconfig and
/// Core Text. A build with `system` off has none, so allow it to go unused
/// there.
#[allow(dead_code)]
pub(crate) fn sample_scripts() -> impl Iterator<Item = Script> {
    SAMPLES.iter().map(|(tag, _)| Script::from_bytes(*tag))
}

/// Representative codepoints for `script`, or empty if we have none.
pub(crate) fn sample_codepoints(script: Script) -> &'static [u32] {
    match SAMPLES.binary_search_by_key(&key(script), |(tag, _)| u32::from_be_bytes(*tag)) {
        Ok(i) => SAMPLES[i].1,
        Err(_) => &[],
    }
}

/// Returns the scripts with a sample far less supported than its siblings,
/// given how many installed fonts carry each codepoint.
///
/// Each platform's coverage test calls it with that platform's counts.
///
/// The rule — first eight assigned letters — has no notion of how
/// *established* a character is, so it lands on things almost nothing
/// implements. It has done so four times: U+0620 for Arabic (Unicode 6.0,
/// Kashmiri only), U+0E86 and U+0E89 for Lao (12.0), U+1408 for Canadian
/// Aboriginal, and Meetei Mayek's extension block. Each one demoted fonts
/// that draw the script perfectly well, because `FC_CHARSET` puts these
/// codepoints in front of fontconfig, and a codepoint a font lacks is a
/// codepoint that costs it.
///
/// Half the best-supported sibling is the threshold. A third was tried first
/// and let U+0620 through by a whisker — 36 fonts carry it against its
/// siblings' 103 — so it only ever caught that case because the numbers
/// happened to sit just under the line on one machine. Real variation within
/// a script's core letters is far narrower than half.
///
/// A sample *no* installed font carries is not a finding. The backend sorts
/// with `FcFontSort`'s trim set, and both the ordering and the trim turn on
/// how much of the requested charset each candidate supplies: a codepoint
/// none of them has is a point none of them scores, so it cannot reorder them
/// and cannot trim any of them away. Only a sample a *minority* carries
/// misranks, which is exactly what U+0620 did. Judging the script's worst
/// sample against its best instead flagged Dives Akuru on a stock Fedora 44,
/// where one font covers the script and half the samples sit at zero — a
/// complaint about the font's completeness, not the table's.
#[cfg(test)]
#[allow(dead_code)] // no checker without `system`; see `scripts`
pub(crate) fn report_outliers(
    covering: impl Fn(u32) -> usize,
) -> alloc::vec::Vec<alloc::string::String> {
    use alloc::string::String;
    use alloc::vec::Vec;

    let mut suspect = Vec::new();
    for script in sample_scripts() {
        let cps = sample_codepoints(script);
        let counts: Vec<usize> = cps.iter().map(|&c| covering(c)).collect();
        let Some(&max) = counts.iter().max() else {
            continue;
        };
        // Nothing installed covers this script, so there is nothing to judge.
        if max == 0 {
            continue;
        }
        // Carried by some, but far from the best-supported sibling.
        if !counts.iter().any(|&n| n > 0 && n * 2 < max) {
            continue;
        }
        let detail: Vec<String> = cps
            .iter()
            .zip(&counts)
            .map(|(c, n)| alloc::format!("U+{c:04X}={n}"))
            .collect();
        suspect.push(alloc::format!("{}: {}", script, detail.join(" ")));
    }
    suspect
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_is_sorted_and_populated() {
        for pair in SAMPLES.windows(2) {
            assert!(
                pair[0].0 < pair[1].0,
                "out of order at {:?}",
                Script::from_bytes(pair[1].0)
            );
        }
        assert!(SAMPLES.iter().all(|(_, cps)| !cps.is_empty()));
    }

    /// Regenerates the table from the Unicode data and fails if it drifted.
    ///
    /// Overridden entries are exempt; everything else must still be the first
    /// eight assigned letters of its script.
    #[test]
    fn generated_entries_still_match_unicode() {
        use alloc::collections::BTreeMap;
        use alloc::vec::Vec;
        use icu_properties::CodePointMapData;
        use icu_properties::props::{
            GeneralCategory, NamedEnumeratedProperty, Script as IcuScript,
        };

        let scripts = CodePointMapData::<IcuScript>::new();
        let categories = CodePointMapData::<GeneralCategory>::new();
        let mut generated: BTreeMap<&'static str, Vec<u32>> = BTreeMap::new();
        for ch in (0..=0x10FFFF_u32).filter_map(char::from_u32) {
            if !matches!(
                categories.get(ch),
                GeneralCategory::UppercaseLetter
                    | GeneralCategory::LowercaseLetter
                    | GeneralCategory::TitlecaseLetter
                    | GeneralCategory::ModifierLetter
                    | GeneralCategory::OtherLetter
            ) {
                continue;
            }
            let entry = generated.entry(scripts.get(ch).short_name()).or_default();
            if entry.len() < 8 {
                entry.push(ch as u32);
            }
        }

        for (name, expected) in generated {
            let Ok(script) = Script::parse(name) else {
                continue;
            };
            if OVERRIDDEN.contains(&script.to_bytes()) || matches!(name, "Zyyy" | "Zinh" | "Zzzz") {
                continue;
            }
            assert_eq!(
                sample_codepoints(script),
                expected.as_slice(),
                "{name} drifted; regenerate it or add it to OVERRIDDEN with a reason"
            );
        }
    }

    #[test]
    fn combined_codes_are_present() {
        // These are CLDR codes with no Script property value, so the
        // generator never produces them; they have to be maintained by hand.
        for tag in [b"Hans", b"Hant", b"Jpan", b"Kore"] {
            assert!(
                !sample_codepoints(Script::from_bytes(*tag)).is_empty(),
                "missing {tag:?}"
            );
        }
    }
}
